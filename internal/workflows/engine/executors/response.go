package executors

import (
	"context"
	"fmt"

	"github.com/everstacklabs/everstack/internal/workflows/engine"
)

// ResponseExecutor handles the terminal response node -- formats the final response.
type ResponseExecutor struct{}

func (e *ResponseExecutor) NodeType() string { return "response" }

func (e *ResponseExecutor) Execute(ctx context.Context, node *engine.GraphNode, ec *engine.ExecutionContext) engine.NodeResult {
	// The response node is terminal -- it signals the end of execution.
	// The actual response content was already set by the provider node
	// or accumulated from streaming chunks.
	// Note: StreamingEnabled is set upfront before engine execution begins
	// by pre-scanning the graph for this node's config.

	ec.SetNodeData("streaming", fmt.Sprintf("%v", ec.StreamingEnabled))

	output := map[string]interface{}{
		"streaming": ec.StreamingEnabled,
	}

	// Check for audio output from upstream nodes (TTS, VoiceClone).
	if audioB64 := resolveAudioVariable(ec); audioB64 != "" {
		output["audio"] = audioB64
		ec.SetNodeData("audio", audioB64)
		ec.SetNodeData("type", "audio")

		if f, ok := ec.Variables["voice_clone_format"]; ok {
			output["format"] = f
			ec.SetNodeData("format", fmt.Sprintf("%v", f))
			ec.SetNodeData("content_type", fmt.Sprintf("audio/%v", f))
		} else if f, ok := ec.Variables["tts_format"]; ok {
			output["format"] = f
			ec.SetNodeData("format", fmt.Sprintf("%v", f))
			ec.SetNodeData("content_type", fmt.Sprintf("audio/%v", f))
		}
		return engine.NodeResult{NextHandle: "", Output: output}
	}

	if ec.Response == nil && !ec.StreamingEnabled {
		// No response set -- this means no provider node was hit
		return engine.NodeResult{Error: fmt.Errorf("no response generated by workflow")}
	}

	if ec.Response != nil && len(ec.Response.Choices) > 0 {
		msg := ec.Response.Choices[0].Message
		if len(msg.Content) > 0 && msg.Content[0].Text != nil {
			ec.SetNodeData("content_length", fmt.Sprintf("%d", len(*msg.Content[0].Text)))
			output["content"] = *msg.Content[0].Text
		}
	}

	return engine.NodeResult{NextHandle: "", Output: output}
}

// resolveAudioVariable checks ec.Variables for audio output from TTS or VoiceClone nodes.
func resolveAudioVariable(ec *engine.ExecutionContext) string {
	for _, key := range []string{"voice_clone_audio", "tts_audio"} {
		if v, ok := ec.Variables[key]; ok {
			if s, ok := v.(string); ok && s != "" {
				return s
			}
		}
	}
	return ""
}
