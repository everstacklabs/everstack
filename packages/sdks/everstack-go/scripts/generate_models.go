//go:build ignore

// Generates catalog/models.go from model-catalog/providers.
//
// Usage: go run scripts/generate_models.go
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"sort"
	"strings"
	"time"

	"gopkg.in/yaml.v3"
)

type model struct {
	Name            string   `yaml:"name"`
	DisplayName     string   `yaml:"display_name"`
	Capabilities    []string `yaml:"capabilities"`
	MaxTokens       int      `yaml:"max_tokens"`
	InputCostPer1K  float64  `yaml:"input_cost_per_1k"`
	OutputCostPer1K float64  `yaml:"output_cost_per_1k"`
	Status          string   `yaml:"status"`
	Cost            cost     `yaml:"cost"`
	Limits          limits   `yaml:"limits"`
}

type cost struct {
	InputPer1K  float64 `yaml:"input_per_1k"`
	OutputPer1K float64 `yaml:"output_per_1k"`
}

type limits struct {
	MaxTokens int `yaml:"max_tokens"`
}

type provider struct {
	ID          string  `yaml:"-"`
	Name        string  `yaml:"name"`
	DisplayName string  `yaml:"display_name"`
	BaseURL     string  `yaml:"base_url"`
	Models      []model `yaml:"models"`
}

type catalog struct {
	Providers map[string]provider
}

type manifest struct {
	Version     string `yaml:"version"`
	GeneratedAt string `yaml:"generated_at"`
}

var nonAlpha = regexp.MustCompile(`[^a-zA-Z0-9]+`)

func toConstName(providerID, modelName string) string {
	// e.g. "openai", "gpt-4o" -> "OpenAI_GPT4o"
	p := toTitle(providerID)
	m := toTitle(modelName)
	return p + "_" + m
}

func toTitle(s string) string {
	parts := nonAlpha.Split(s, -1)
	out := make([]string, 0, len(parts))
	for _, p := range parts {
		if p == "" {
			continue
		}
		// Keep well-known abbreviations uppercase
		upper := strings.ToUpper(p)
		switch upper {
		case "AI", "API", "ID", "URL", "GPT", "VL", "LLM":
			out = append(out, upper)
		default:
			out = append(out, strings.ToUpper(p[:1])+p[1:])
		}
	}
	return strings.Join(out, "")
}

func main() {
	scriptDir := scriptDirectory()
	catalogPath := os.Getenv("EVERSTACK_MODEL_CATALOG_PATH")
	if catalogPath == "" {
		catalogPath = filepath.Join(scriptDir, "..", "..", "..", "..", "model-catalog")
	}
	outputPath := filepath.Join(scriptDir, "..", "catalog", "models.go")

	cat, err := loadCatalog(catalogPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Load catalog: %v\n", err)
		os.Exit(1)
	}
	meta := loadManifest(catalogPath)

	var b strings.Builder

	b.WriteString("// Code generated by scripts/generate_models.go; DO NOT EDIT.\n")
	if meta.Version != "" {
		b.WriteString(fmt.Sprintf("// Catalog version: %s\n", meta.Version))
	} else {
		b.WriteString("// Catalog version: unknown\n")
	}
	if meta.GeneratedAt != "" {
		b.WriteString(fmt.Sprintf("// Catalog generated: %s\n\n", meta.GeneratedAt))
	} else {
		b.WriteString(fmt.Sprintf("// Catalog generated: %s\n\n", time.Now().UTC().Format(time.RFC3339)))
	}
	b.WriteString("package catalog\n\n")

	// Collect providers sorted
	providerIDs := make([]string, 0, len(cat.Providers))
	for id := range cat.Providers {
		providerIDs = append(providerIDs, id)
	}
	sort.Strings(providerIDs)

	// Model constants
	b.WriteString("// Model ID constants.\nconst (\n")
	total := 0
	for _, pid := range providerIDs {
		p := cat.Providers[pid]
		active := filterActive(p.Models)
		if len(active) == 0 {
			continue
		}
		sort.Slice(active, func(i, j int) bool { return active[i].Name < active[j].Name })
		b.WriteString(fmt.Sprintf("\t// %s\n", providerDisplayName(p)))
		for _, m := range active {
			constName := toConstName(pid, m.Name)
			b.WriteString(fmt.Sprintf("\t%s = \"@%s/%s\"\n", constName, pid, m.Name))
			total++
		}
		b.WriteString("\n")
	}
	b.WriteString(")\n\n")

	// ModelMetadata struct
	b.WriteString(`// ModelMetadata holds information about a model.
type ModelMetadata struct {
	ID           string
	Provider     string
	Model        string
	DisplayName  string
	Capabilities []string
	MaxTokens    int
	Status       string
}

`)

	// AllModels slice
	b.WriteString("// AllModels contains metadata for all available models.\n")
	b.WriteString("var AllModels = []ModelMetadata{\n")
	for _, pid := range providerIDs {
		p := cat.Providers[pid]
		active := filterActive(p.Models)
		sort.Slice(active, func(i, j int) bool { return active[i].Name < active[j].Name })
		for _, m := range active {
			caps := make([]string, len(m.Capabilities))
			for i, c := range m.Capabilities {
				caps[i] = fmt.Sprintf("%q", c)
			}
			b.WriteString(fmt.Sprintf("\t{ID: \"@%s/%s\", Provider: %q, Model: %q, DisplayName: %q, Capabilities: []string{%s}, MaxTokens: %d, Status: %q},\n",
				pid, m.Name, pid, m.Name, m.DisplayName,
				strings.Join(caps, ", "), m.MaxTokens, m.Status))
		}
	}
	b.WriteString("}\n\n")

	// Helper functions
	b.WriteString(`// GetMetadata returns metadata for a model ID, or false if not found.
func GetMetadata(modelID string) (ModelMetadata, bool) {
	for _, m := range AllModels {
		if m.ID == modelID {
			return m, true
		}
	}
	return ModelMetadata{}, false
}

// ListByProvider returns all models for a provider.
func ListByProvider(provider string) []ModelMetadata {
	var result []ModelMetadata
	for _, m := range AllModels {
		if m.Provider == provider {
			result = append(result, m)
		}
	}
	return result
}

// IsValid checks if a model ID is in the catalog.
func IsValid(modelID string) bool {
	_, ok := GetMetadata(modelID)
	return ok
}
`)

	if err := os.WriteFile(outputPath, []byte(b.String()), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "Write output: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Generated %s (%d models)\n", outputPath, total)
}

func scriptDirectory() string {
	_, filename, _, ok := runtime.Caller(0)
	if ok {
		return filepath.Dir(filename)
	}

	wd, err := os.Getwd()
	if err != nil {
		fmt.Fprintf(os.Stderr, "Get working directory: %v\n", err)
		os.Exit(1)
	}

	return filepath.Join(wd, "scripts")
}

func loadCatalog(catalogPath string) (catalog, error) {
	providersDir := filepath.Join(catalogPath, "providers")
	entries, err := os.ReadDir(providersDir)
	if err != nil {
		return catalog{}, fmt.Errorf("read providers directory: %w", err)
	}

	cat := catalog{Providers: make(map[string]provider)}
	for _, entry := range entries {
		if !entry.IsDir() {
			continue
		}

		providerID := entry.Name()
		providerDir := filepath.Join(providersDir, providerID)
		providerPath := filepath.Join(providerDir, "provider.yaml")
		data, err := os.ReadFile(providerPath)
		if err != nil {
			return catalog{}, fmt.Errorf("read provider %s: %w", providerID, err)
		}

		var p provider
		if err := yaml.Unmarshal(data, &p); err != nil {
			return catalog{}, fmt.Errorf("parse provider %s: %w", providerID, err)
		}
		p.ID = providerID

		modelsDir := filepath.Join(providerDir, "models")
		models, err := loadModels(modelsDir)
		if err != nil {
			return catalog{}, fmt.Errorf("load models for provider %s: %w", providerID, err)
		}
		p.Models = models

		cat.Providers[providerID] = p
	}

	return cat, nil
}

func loadModels(modelsDir string) ([]model, error) {
	entries, err := os.ReadDir(modelsDir)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("read models directory: %w", err)
	}

	models := make([]model, 0, len(entries))
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".yaml") {
			continue
		}

		modelPath := filepath.Join(modelsDir, entry.Name())
		data, err := os.ReadFile(modelPath)
		if err != nil {
			return nil, fmt.Errorf("read model %s: %w", entry.Name(), err)
		}

		var m model
		if err := yaml.Unmarshal(data, &m); err != nil {
			return nil, fmt.Errorf("parse model %s: %w", entry.Name(), err)
		}
		if m.Name == "" {
			return nil, fmt.Errorf("model file missing name: %s", modelPath)
		}
		if m.DisplayName == "" {
			m.DisplayName = m.Name
		}
		if m.Status == "" {
			m.Status = "stable"
		}
		if m.MaxTokens == 0 {
			m.MaxTokens = m.Limits.MaxTokens
		}
		models = append(models, m)
	}

	return models, nil
}

func loadManifest(catalogPath string) manifest {
	data, err := os.ReadFile(filepath.Join(catalogPath, "manifest.yaml"))
	if err != nil {
		return manifest{}
	}

	var meta manifest
	if err := yaml.Unmarshal(data, &meta); err != nil {
		return manifest{}
	}
	return meta
}

func providerDisplayName(p provider) string {
	if p.DisplayName != "" {
		return p.DisplayName
	}
	if p.Name != "" {
		return p.Name
	}
	return p.ID
}

func filterActive(models []model) []model {
	var out []model
	for _, m := range models {
		if m.Status != "deprecated" {
			out = append(out, m)
		}
	}
	return out
}
