/**
 * Chat completion types
 *
 * These types are designed to be OpenAI-compatible while supporting
 * type-safe model selection with the Everstack model catalog.
 */

import type {
    FinishReason,
    MessageContent,
    ResponseFormat,
    Role,
    Tool,
    ToolCall,
    ToolChoice,
    Usage,
} from "./common.js";

/**
 * A message in a chat conversation
 */
export interface ChatMessage {
    /** The role of the message author */
    role: Role;
    /** The content of the message */
    content: MessageContent;
    /** An optional name for the participant */
    name?: string;
    /** Tool calls made by the assistant */
    tool_calls?: ToolCall[];
    /** The ID of the tool call this message is responding to */
    tool_call_id?: string;
}

/**
 * System message
 */
export interface SystemMessage {
    role: "system";
    content: string;
    name?: string;
}

/**
 * User message
 */
export interface UserMessage {
    role: "user";
    content: MessageContent;
    name?: string;
}

/**
 * Assistant message
 */
export interface AssistantMessage {
    role: "assistant";
    content: string | null;
    name?: string;
    tool_calls?: ToolCall[];
}

/**
 * Tool message (response to a tool call)
 */
export interface ToolMessage {
    role: "tool";
    content: string;
    tool_call_id: string;
}

/**
 * Union of all message types
 */
export type Message = SystemMessage | UserMessage | AssistantMessage | ToolMessage;

/**
 * Parameters for a chat completion request
 */
export interface ChatCompletionParams<TModel extends string = string> {
    /** ID of the model to use (e.g., "@openai/gpt-4o") */
    model: TModel;

    /** A list of messages comprising the conversation */
    messages: Message[];

    /** Sampling temperature (0-2) */
    temperature?: number;

    /** Nucleus sampling parameter */
    top_p?: number;

    /** Maximum tokens to generate */
    max_tokens?: number;

    /** Maximum completion tokens (alias for max_tokens) */
    max_completion_tokens?: number;

    /** Stop sequences */
    stop?: string | string[];

    /** Whether to stream the response */
    stream?: boolean;

    /** Presence penalty (-2 to 2) */
    presence_penalty?: number;

    /** Frequency penalty (-2 to 2) */
    frequency_penalty?: number;

    /** Modify likelihood of specific tokens */
    logit_bias?: Record<string, number>;

    /** Number of completions to generate */
    n?: number;

    /** A unique identifier for the end-user */
    user?: string;

    /** Response format configuration */
    response_format?: ResponseFormat;

    /** Tools available to the model */
    tools?: Tool[];

    /** How the model should use tools */
    tool_choice?: ToolChoice;

    /** Seed for deterministic sampling */
    seed?: number;

    /** Custom metadata for logging/tracking */
    metadata?: Record<string, unknown>;
}

/**
 * A choice in a chat completion response
 */
export interface ChatCompletionChoice {
    /** The index of this choice */
    index: number;

    /** The message generated by the model */
    message: AssistantMessage;

    /** The reason the model stopped generating */
    finish_reason: FinishReason;

    /** Log probabilities (if requested) */
    logprobs?: {
        content: Array<{
            token: string;
            logprob: number;
            bytes?: number[];
            top_logprobs?: Array<{ token: string; logprob: number; bytes?: number[] }>;
        }> | null;
    } | null;
}

/**
 * Fallback information when a model is unavailable
 */
export interface FallbackInfo {
    /** Whether fallback was used */
    fallback_used: boolean;
    /** The originally requested model */
    requested_model: string;
    /** The model that actually served the request */
    actual_model: string;
    /** Reason for fallback */
    fallback_reason?: string;
    /** Number of fallback attempts */
    fallback_attempts?: number;
}

/**
 * A chat completion response
 */
export interface ChatCompletionResponse {
    /** Unique identifier for this completion */
    id: string;

    /** Object type (always "chat.completion") */
    object: "chat.completion";

    /** Unix timestamp of when the completion was created */
    created: number;

    /** The model used for the completion */
    model: string;

    /** The list of completion choices */
    choices: ChatCompletionChoice[];

    /** Token usage statistics */
    usage: Usage;

    /** System fingerprint */
    system_fingerprint?: string;

    /** Fallback information (Everstack-specific) */
    fallback_info?: FallbackInfo;
}

/**
 * A delta in a streaming chat completion
 */
export interface ChatCompletionDelta {
    /** Role (only present in first chunk) */
    role?: Role;
    /** Content fragment */
    content?: string | null;
    /** Tool calls (streamed incrementally) */
    tool_calls?: Array<{
        index: number;
        id?: string;
        type?: "function";
        function?: {
            name?: string;
            arguments?: string;
        };
    }>;
}

/**
 * A choice in a streaming chat completion chunk
 */
export interface ChatCompletionChunkChoice {
    /** The index of this choice */
    index: number;
    /** The delta for this chunk */
    delta: ChatCompletionDelta;
    /** The reason the model stopped (only in final chunk) */
    finish_reason: FinishReason;
    /** Log probabilities */
    logprobs?: ChatCompletionChoice["logprobs"];
}

/**
 * A streaming chat completion chunk
 */
export interface ChatCompletionChunk {
    /** Unique identifier for this completion */
    id: string;
    /** Object type (always "chat.completion.chunk") */
    object: "chat.completion.chunk";
    /** Unix timestamp of when the chunk was created */
    created: number;
    /** The model used for the completion */
    model: string;
    /** The list of chunk choices */
    choices: ChatCompletionChunkChoice[];
    /** System fingerprint */
    system_fingerprint?: string;
    /** Usage (only in final chunk if requested) */
    usage?: Usage | null;
}
